import { spawn } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const stateDir = fs.mkdtempSync(path.join(os.tmpdir(), "veto-demo-"));
const logPath = path.join(root, "examples", "sensitive-command-approval.log");

const baseEnv: NodeJS.ProcessEnv = {
  ...process.env,
  MOCK_CIBA: "1",
  MOCK_GITHUB: "1",
  CIBA_STATE_DIR: stateDir,
  CIBA_POLL_INTERVAL_SEC: "0.3",
  CIBA_REQUESTED_EXPIRY: "30",
  AUTH0_DOMAIN: "dev-wvxvhbnjrgvgn26x.us.auth0.com",
  AUTH0_CLIENT_ID: "your-client-id",
  AUTH0_CLIENT_SECRET: "your-client-secret",
  AUTH0_USER_ID: "auth0|your-user-id",
  AUTH0_REFRESH_TOKEN: "your-auth0-refresh-token",
};

type Captured = { code: number; output: string };

function run(args: string[]): Promise<Captured> {
  return new Promise((resolve, reject) => {
    const child = spawn(process.execPath, ["--import", "tsx", "src/cli.ts", ...args], {
      cwd: root,
      env: baseEnv,
    });
    let output = "";
    child.stdout.on("data", (chunk: Buffer) => {
      output += chunk.toString("utf8");
    });
    child.stderr.on("data", (chunk: Buffer) => {
      output += chunk.toString("utf8");
    });
    child.on("error", reject);
    child.on("close", (code) => resolve({ code: code ?? 1, output }));
  });
}

function runUntilPending(
  args: string[],
  pendingCount: number,
): Promise<{ child: ReturnType<typeof spawn>; output: () => string }> {
  return new Promise((resolve, reject) => {
    const child = spawn(process.execPath, ["--import", "tsx", "src/cli.ts", ...args], {
      cwd: root,
      env: baseEnv,
    });
    let output = "";
    let settled = false;
    const timer = setTimeout(() => {
      child.kill();
      reject(new Error(`timed out waiting for CIBA halt\n${output}`));
    }, 20000);
    child.stdout.on("data", (chunk: Buffer) => {
      output += chunk.toString("utf8");
      if (settled) return;
      const seen = output.split("authorization_pending").length - 1;
      if (seen >= pendingCount) {
        settled = true;
        clearTimeout(timer);
        resolve({ child, output: () => output });
      }
    });
    child.stderr.on("data", (chunk: Buffer) => {
      output += chunk.toString("utf8");
    });
    child.on("error", (err) => {
      clearTimeout(timer);
      reject(err);
    });
    child.on("close", (code) => {
      if (settled) return;
      clearTimeout(timer);
      reject(new Error(`agent exited early (${code})\n${output}`));
    });
  });
}

function waitForClose(child: ReturnType<typeof spawn>, getOutput: () => string): Promise<Captured> {
  return new Promise((resolve, reject) => {
    const timer = setTimeout(() => {
      child.kill();
      reject(new Error(`timed out waiting for the agent to resume\n${getOutput()}`));
    }, 20000);
    child.on("close", (code) => {
      clearTimeout(timer);
      resolve({ code: code ?? 1, output: getOutput() });
    });
  });
}

function authReqId(output: string): string {
  const match = output.match(/auth_req_id=(ciba_[0-9a-f]+)/);
  if (!match?.[1]) throw new Error(`no auth_req_id in output\n${output}`);
  return match[1];
}

function section(title: string, command: string, output: string): string {
  return [`===== ${title} =====`, `$ veto ${command}`, output.trimEnd(), ""].join("\n");
}

async function main(): Promise<void> {
  const parts: string[] = [
    "# The Veto Agent — example run",
    "# MOCK_CIBA=1 MOCK_GITHUB=1 (no Auth0 or GitHub credentials)",
    "# A delete halts on authorization_pending until another terminal approves it.",
    `# Generated by npm run demo:approval`,
    "",
  ];

  const listed = await run(["list", "repos"]);
  if (listed.code !== 0) throw new Error(listed.output);
  parts.push(section("1. list repos (read — no approval)", "list repos", listed.output));

  const issues = await run(["list", "open", "issues", "in", "acme/widgets"]);
  if (issues.code !== 0) throw new Error(issues.output);
  parts.push(section("2. list open issues (read — no approval)", "list open issues in acme/widgets", issues.output));

  const deleting = await runUntilPending(["delete", "repo", "acme/widgets"], 2);
  const halted = deleting.output();
  const deleteId = authReqId(halted);
  parts.push(section("3. delete repo (high-impact — agent halts)", "delete repo acme/widgets", halted));

  const approved = await run(["approve", deleteId]);
  if (approved.code !== 0) throw new Error(approved.output);
  parts.push(section("4. out-of-band approval (other terminal)", `approve ${deleteId}`, approved.output));

  const resumed = await waitForClose(deleting.child, deleting.output);
  if (resumed.code !== 0) throw new Error(resumed.output);
  const resumeOnly = resumed.output.slice(halted.length);
  parts.push(section("5. agent resumes after approval", "(same delete command)", resumeOnly));

  const archiving = await runUntilPending(["archive", "repo", "acme/notes"], 1);
  const archiveHalted = archiving.output();
  const archiveId = authReqId(archiveHalted);
  parts.push(section("6. archive repo (high-impact — agent halts again)", "archive repo acme/notes", archiveHalted));

  const denied = await run(["deny", archiveId]);
  if (denied.code !== 0) throw new Error(denied.output);
  parts.push(section("7. out-of-band denial", `deny ${archiveId}`, denied.output));

  const archiveDone = await waitForClose(archiving.child, archiving.output);
  if (archiveDone.code !== 2) {
    throw new Error(`expected denial exit code 2, got ${archiveDone.code}\n${archiveDone.output}`);
  }
  parts.push(
    section("8. agent stops without archiving", "(same archive command)", archiveDone.output.slice(archiveHalted.length)),
  );

  const after = await run(["list", "repos"]);
  if (after.code !== 0) throw new Error(after.output);
  if (after.output.includes("acme/widgets")) {
    throw new Error("widgets repository was still present after an approved delete");
  }
  if (!after.output.includes("archived=false")) {
    throw new Error("notes repository was archived after a denial");
  }
  parts.push(section("9. list repos after the veto", "list repos", after.output));

  fs.mkdirSync(path.dirname(logPath), { recursive: true });
  fs.writeFileSync(logPath, parts.join("\n"));
  fs.rmSync(stateDir, { recursive: true, force: true });
  console.log(`wrote ${path.relative(root, logPath)}`);
}

main().catch((err: unknown) => {
  console.error(err instanceof Error ? err.message : err);
  process.exitCode = 1;
});
